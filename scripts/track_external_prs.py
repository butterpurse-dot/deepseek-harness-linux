#!/usr/bin/env python3
"""Surface review activity on external pull requests as a repo issue.

The project owner does not want to watch email. This script runs on a schedule,
finds open PRs authored by the tracked account in other repositories, and keeps
one issue in this repository updated with the latest external comment.
"""
from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timezone

API = "https://api.github.com"
TOKEN = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
REPO = os.environ.get("GITHUB_REPOSITORY", "butterpurse-dot/deepseek-harness-linux")
AUTHOR = os.environ.get("TRACK_AUTHOR", "butterpurse-dot")
ISSUE_TITLE = "External PR review queue"
ISSUE_LABEL = "external-pr"
BOT_LOGINS = {AUTHOR, "github-actions[bot]", "dependabot[bot]"}


def request(path: str, method: str = "GET", body: dict | None = None):
    if not TOKEN:
        raise SystemExit("GH_TOKEN or GITHUB_TOKEN is required")
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(
        API + path,
        data=data,
        method=method,
        headers={
            "Authorization": f"Bearer {TOKEN}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "deepseek-harness-linux-pr-tracker",
            "Content-Type": "application/json",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            payload = response.read()
            return json.loads(payload) if payload else None
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return None
        raise


def search_open_prs() -> list[dict]:
    query = urllib.parse.quote(f"is:pr is:open author:{AUTHOR}")
    result = request(f"/search/issues?q={query}&per_page=100")
    return (result or {}).get("items", [])


def events_for(repo: str, number: int) -> list[tuple[str, str, str, str]]:
    events: list[tuple[str, str, str, str]] = []
    for comment in request(f"/repos/{repo}/issues/{number}/comments?per_page=100") or []:
        events.append((comment["created_at"], comment["user"]["login"], comment.get("body") or "", comment["html_url"]))
    for review in request(f"/repos/{repo}/pulls/{number}/reviews?per_page=100") or []:
        if review.get("submitted_at"):
            state = review.get("state", "review").lower()
            events.append((review["submitted_at"], review["user"]["login"], review.get("body") or f"Review: {state}", review["html_url"]))
    for comment in request(f"/repos/{repo}/pulls/{number}/comments?per_page=100") or []:
        events.append((comment["created_at"], comment["user"]["login"], comment.get("body") or "", comment["html_url"]))
    return events


def build_body(rows: list[dict]) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "<!-- generated by scripts/track_external_prs.py -->",
        "# External PR review queue",
        "",
        f"Updated {now}. This issue is the alert for review activity on pull requests "
        f"opened from `{AUTHOR}` in other repositories. Ask the agent to check this queue "
        "and it will address the comments.",
        "",
    ]
    if not rows:
        lines.append("No open external pull requests.")
        return "\n".join(lines) + "\n"
    lines += ["| PR | Repository | Last external activity |", "|---|---|---|"]
    for row in rows:
        activity = row["activity"]
        if activity is None:
            activity = "waiting for review"
        else:
            when, who, body, url = activity
            excerpt = " ".join(body.split())
            if len(excerpt) > 180:
                excerpt = excerpt[:177] + "..."
            activity = f"[{who} · {when[:10]}]({url}): {excerpt or '(no text)'}"
        lines.append(f"| [#{row['number']} {row['title']}]({row['url']}) | `{row['repo']}` | {activity} |")
    return "\n".join(lines) + "\n"


def ensure_label() -> None:
    request(f"/repos/{REPO}/labels", "POST", {
        "name": ISSUE_LABEL,
        "color": "1d76db",
        "description": "Review activity on external pull requests",
    })


def find_issue() -> dict | None:
    issues = request(f"/repos/{REPO}/issues?labels={ISSUE_LABEL}&state=open&per_page=10") or []
    return issues[0] if issues else None


def main() -> None:
    rows = []
    for item in search_open_prs():
        repo = item["repository_url"].split("/repos/", 1)[1]
        if repo == REPO or repo.split("/", 1)[0] == AUTHOR:
            continue
        external = [
            event for event in events_for(repo, item["number"])
            if event[1] not in BOT_LOGINS
        ]
        external.sort(key=lambda event: event[0])
        rows.append({
            "repo": repo,
            "number": item["number"],
            "title": item["title"],
            "url": item["html_url"],
            "activity": external[-1] if external else None,
        })
    rows.sort(key=lambda row: (row["activity"] is None, row["repo"], row["number"]))
    body = build_body(rows)
    issue = find_issue()
    if issue is None:
        ensure_label()
        created = request(f"/repos/{REPO}/issues", "POST", {
            "title": ISSUE_TITLE,
            "body": body,
            "labels": [ISSUE_LABEL],
        })
        print(f"created issue {created['html_url']}")
        return
    if issue.get("body") == body:
        print("no changes")
        return
    updated = request(f"/repos/{REPO}/issues/{issue['number']}", "PATCH", {"body": body})
    print(f"updated issue {updated['html_url']}")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:  # noqa: BLE001 - surface the failure in the workflow log
        print(f"track-external-prs: {error}", file=sys.stderr)
        raise
